/**
 * Extract the ABIs the frontend needs from Foundry's build output.
 *
 * Wired into `prebuild`, so a contract change the frontend has not caught up
 * with fails the build instead of failing at runtime in someone's wallet.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "contracts", "out");
const dest = join(here, "..", "lib", "abis");

const WANTED = [
  ["ErodoroVault.sol", "ErodoroVault"],
  ["Factory.sol", "Factory"],
  ["ErodoroRFQ.sol", "ErodoroRFQ"],
  ["ErodoroIntent.sol", "ErodoroIntent"],
  ["MarketRipPool.sol", "MarketRipPool"],
  ["MarketRipPut.sol", "MarketRipPut"],
  ["TestFaucet.sol", "TestFaucet"],
  ["TestIssuerControls.sol", "TestIssuerControls"],
  ["IB20Asset.sol", "IB20Asset"],
  ["IPolicyRegistry.sol", "IPolicyRegistry"],
  ["IFallbackSettlementOracle.sol", "IFallbackSettlementOracle"],
];

if (!existsSync(out)) {
  console.error(`No Foundry artifacts at ${out}. Run \`forge build\` in contracts/ first.`);
  process.exit(1);
}

mkdirSync(dest, { recursive: true });
const index = [];

for (const [file, name] of WANTED) {
  const artifact = join(out, file, `${name}.json`);
  if (!existsSync(artifact)) {
    console.error(`Missing artifact: ${artifact}`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by scripts/gen-abis.mjs. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${name}Abi } from "./${name}";`);
  console.log(`  ${name}: ${abi.length} entries`);
}

writeFileSync(join(dest, "index.ts"), `// Generated by scripts/gen-abis.mjs. Do not edit.\n${index.join("\n")}\n`);
console.log("ABIs written to lib/abis/");
